  function cleanTextForSpeech(rawText) {
    if (!rawText) return "";
    return String(rawText)
      .replace(/<[^>]*>/g, " ")
      .replace(/\*\*\[.*?\]\*\*/g, "")
      .replace(/[*_#`~>]/g, "")
      .replace(/•/g, ". ")
      .replace(/[\u{1F300}-\u{1F9FF}\u{2600}-\u{26FF}\u{2700}-\u{27BF}]/gu, "")
      .replace(/\s+/g, " ")
      .trim();
  }

  function stopSpeechPlayback() {
    if (activeAudio) {
      try {
        activeAudio.pause();
        activeAudio.currentTime = 0;
      } catch (e) {}
      activeAudio = null;
    }
    if (window.speechSynthesis) {
      try {
        window.speechSynthesis.cancel();
      } catch (e) {}
    }
    if (activeSpeakBtn) {
      activeSpeakBtn.classList.remove("speaking");
      activeSpeakBtn.innerHTML = t("voice.speak_btn");
      activeSpeakBtn = null;
    }
    document.querySelectorAll(".orca-speak-btn.speaking").forEach(btn => {
      btn.classList.remove("speaking");
      btn.innerHTML = t("voice.speak_btn");
    });
  }

  function speakViaBrowserFallback(cleanText, langCode, btnEl) {
    if (!window.speechSynthesis) {
      stopSpeechPlayback();
      return;
    }
    try {
      window.speechSynthesis.cancel();
      const utter = new SpeechSynthesisUtterance(cleanText);
      const bcp = BCP47_MAP[langCode] || "en-IN";
      utter.lang = bcp;

      const voices = window.speechSynthesis.getVoices() || [];
      const prefix = langCode.toLowerCase();
      const matchedVoice =
        voices.find(v => v.lang && v.lang.toLowerCase() === bcp.toLowerCase()) ||
        voices.find(v => v.lang && v.lang.toLowerCase().startsWith(prefix));
      if (matchedVoice) {
        utter.voice = matchedVoice;
      }

      utter.onend = () => {
        stopSpeechPlayback();
      };
      utter.onerror = () => {
        stopSpeechPlayback();
      };

      window.speechSynthesis.speak(utter);
    } catch (e) {
      stopSpeechPlayback();
    }
  }

  function speakText(rawText, btnEl, langOverride) {
    // If clicking the same button that is already speaking, stop immediately
    if (btnEl && btnEl.classList.contains("speaking")) {
      stopSpeechPlayback();
      return;
    }

    stopSpeechPlayback();

    const clean = cleanTextForSpeech(rawText);
    if (!clean) return;

    const lang = langOverride || currentLang || "en";
    activeSpeakBtn = btnEl;
    if (btnEl) {
      btnEl.classList.add("speaking");
      btnEl.innerHTML = t("voice.stop_btn");
    }

    const host = window.location.hostname || "127.0.0.1";
    const ttsUrl = `http://${host}:8000/api/v1/agent/tts?lang=${encodeURIComponent(lang)}&text=${encodeURIComponent(clean.slice(0, 900))}`;

    // Use backend API TTS stream first so all 11 Indian languages speak with authentic pronunciation,
    // and fall back automatically to browser speechSynthesis if backend is unreachable.
    const audio = new Audio(ttsUrl);
    activeAudio = audio;

    audio.onended = () => {
      stopSpeechPlayback();
    };

    audio.onerror = () => {
      if (activeAudio !== audio) return;
      activeAudio = null;
      speakViaBrowserFallback(clean, lang, btnEl);
    };

    audio.play().catch(() => {
      if (activeAudio !== audio) return;
      activeAudio = null;
      speakViaBrowserFallback(clean, lang, btnEl);
    });
  }


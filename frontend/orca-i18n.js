  function setLanguage(langCode) {
    if (!langCode || LANG_INDEX[langCode] === undefined) return;
    currentLang = langCode;
    try {
      localStorage.setItem("orca_lang", currentLang);
    } catch (e) {}

    // Stop any ongoing speech/listening when switching language
    stopSpeechPlayback();
    if (isListening) stopVoiceInput();

    // Sync dropdowns if multiple exist
    document.querySelectorAll(".orca-lang-select").forEach(sel => {
      if (sel.value !== currentLang) sel.value = currentLang;
    });

    applyUITranslations();

    window.dispatchEvent(new CustomEvent("orca:languagechange", { detail: { language: currentLang } }));
  }

